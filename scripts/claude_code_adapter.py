class JsonArgumentParser(argparse.ArgumentParser):
    def error(self, message: str) -> None:
        emit({"status": "error", "error": message})
        raise SystemExit(2)


def emit(value: Mapping[str, Any]) -> None:
    payload = {"host": HOST, **value}
    if CATALOG_NOTICE is not None:
        payload.setdefault("catalog_notice", CATALOG_NOTICE)
    data = (json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + "\n").encode("utf-8")
    out = getattr(sys.stdout, "buffer", None)
    if out is not None:
        out.write(data)
        out.flush()
    else:
        sys.stdout.write(data.decode("utf-8"))


def _read_json(path: Path, label: str) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8-sig"))
    except FileNotFoundError as exc:
        raise AdapterError(f"{label} not found: {path}") from exc
    except (OSError, json.JSONDecodeError) as exc:
        raise AdapterError(f"cannot read {label} at {path}: {exc}") from exc


def _dump(value: Any) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def _csv(value: str | None) -> list[str] | None:
    if value is None:
        return None
    return [item.strip() for item in value.split(",") if item.strip()]


# ---------------------------------------------------------------- catalog

def _dispatch_path(state_dir: Path) -> Path:
    return state_dir / "dispatch.json"


def dispatch_enum(state_dir: Path) -> dict[str, Any]:
    """Last dispatch-tool enum supplied by the caller, or unverified defaults."""
    path = _dispatch_path(state_dir)
    if path.exists():
        data = _read_json(path, "dispatch enum")
        if isinstance(data, dict) and isinstance(data.get("models"), list):
            return {**data, "source": "caller_supplied_dispatch_tool"}
    return {"models": list(DEFAULT_DISPATCH_MODELS), "efforts": list(EFFORT_LEVELS),
            "source": "documented_default_unverified"}


def observed_resolutions(claude_home: Path, limit: int = 200) -> dict[str, dict[str, Any]]:
    """Alias -> model id actually used, read from recent subagent telemetry."""
    metas = sorted(claude_home.glob("projects/*/*/subagents/agent-*.meta.json"),
                   key=lambda p: p.stat().st_mtime, reverse=True)[:limit]
    seen: dict[str, dict[str, Any]] = {}
    for meta_path in metas:
        try:
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        alias = meta.get("model")
        if not isinstance(alias, str) or alias in seen:
            continue
        transcript = meta_path.with_name(meta_path.name.replace(".meta.json", ".jsonl"))
        for line in _iter_lines(transcript):
            if line.get("type") == "assistant":
                actual = (line.get("message") or {}).get("model") or line.get("requestedModel")
                if isinstance(actual, str):
                    seen[alias] = {"resolves_to": actual, "observed_at": line.get("timestamp")}
                    break
    return seen


def _iter_lines(path: Path):
    try:
        with path.open(encoding="utf-8") as stream:
            for raw in stream:
                try:
                    item = json.loads(raw)
                except json.JSONDecodeError:
                    continue
                if isinstance(item, dict):
                    yield item
    except OSError:
        return


def build_catalog(state_dir: Path, claude_home: Path, provider: str) -> list[dict[str, Any]]:
    enum = dispatch_enum(state_dir)
    observed = observed_resolutions(claude_home)
    allowed_efforts = [e for e in enum.get("efforts") or EFFORT_LEVELS if e in EFFORT_LEVELS]
    models = []
    for alias in enum["models"]:
        documented = ANTHROPIC_ALIASES.get(alias) if provider == "anthropic" else None
        seen = observed.get(alias)
        resolves_to = (seen or {}).get("resolves_to") or (documented or {}).get("resolves_to")
        efforts: list[str] | None = None
        if documented and (seen is None or seen["resolves_to"] == documented["resolves_to"]):
            efforts = [e for e in documented["efforts"] if e in allowed_efforts]
        models.append({
            "slug": alias,
            "resolves_to": resolves_to,
            "resolution_source": "observed_subagent_telemetry" if seen else (
                "documented_table" if documented else "unknown"),
            "supported_reasoning_levels": efforts,  # None = unknown, never guessed
            "default_effort": (documented or {}).get("default_effort") if efforts else None,
            "context": (documented or {}).get("context"),
        })
    return models


def catalog_sets(models: list[dict[str, Any]]) -> dict[str, set[str]]:
    """Model -> selectable efforts, including the explicit ``inherit`` choices."""
    result: dict[str, set[str]] = {INHERIT: set(EFFORT_LEVELS) | {INHERIT}}
    for item in models:
        levels = item["supported_reasoning_levels"]
        result[item["slug"]] = (set(levels) if levels else set()) | {INHERIT}
    return result


def _fingerprint(models: list[dict[str, Any]]) -> str:
    core = [{"slug": m["slug"], "resolves_to": m["resolves_to"],
             "levels": m["supported_reasoning_levels"]} for m in models]
    return hashlib.sha256(json.dumps(core, sort_keys=True).encode()).hexdigest()


def _changes(old: list[dict[str, Any]], new: list[dict[str, Any]]) -> dict[str, Any]:
    before = {m["slug"]: m for m in old}
    after = {m["slug"]: m for m in new}
    return {
        "added_models": [after[s] for s in sorted(after.keys() - before.keys())],
        "removed_models": [before[s] for s in sorted(before.keys() - after.keys())],
        "changed_models": [
            {"slug": s,
             "previous_resolves_to": before[s].get("resolves_to"), "resolves_to": after[s].get("resolves_to"),
             "previous_reasoning_levels": before[s].get("supported_reasoning_levels"),
             "supported_reasoning_levels": after[s].get("supported_reasoning_levels")}
            for s in sorted(before.keys() & after.keys())
            if (before[s].get("resolves_to"), before[s].get("supported_reasoning_levels"))
            != (after[s].get("resolves_to"), after[s].get("supported_reasoning_levels"))
        ],
    }


def check_catalog(state_dir: Path, models: list[dict[str, Any]]) -> dict[str, Any]:
    path = state_dir / "catalog_state.json"
    fingerprint = _fingerprint(models)
    if not path.exists():
        commit_files({path: _dump({"version": CATALOG_STATE_VERSION, "last_seen_fingerprint": fingerprint,
                                   "last_seen_models": models, "acknowledged": {}, "pending": []})}, state_dir)
        return {"status": "baseline_established", "fingerprint": fingerprint, "pending": []}
    state = _read_json(path, "catalog state")
    if not isinstance(state, dict) or state.get("version") != CATALOG_STATE_VERSION:
        raise AdapterError(f"invalid catalog state; refusing to reset it: {path}")
    if fingerprint != state["last_seen_fingerprint"]:
        known = {item.get("fingerprint") for item in state["pending"]}
        if fingerprint not in state["acknowledged"] and fingerprint not in known:
            state["pending"].append({"fingerprint": fingerprint,
                                     "previous_fingerprint": state["last_seen_fingerprint"],
                                     "changes": _changes(state["last_seen_models"], models)})
        state["last_seen_fingerprint"] = fingerprint
        state["last_seen_models"] = models
        commit_files({path: _dump(state)}, state_dir)
    notice: dict[str, Any] = {"status": "pending_change" if state["pending"] else "unchanged",
                              "fingerprint": fingerprint, "pending": state["pending"]}
    if state["pending"]:
        notice["current_roles"] = _raw_roles(state_dir)
    return notice


def _raw_roles(state_dir: Path) -> dict[str, Any] | None:
    try:
        data = json.loads((state_dir / "profile.json").read_text(encoding="utf-8"))
        return data.get("roles") if isinstance(data, dict) else None
    except (OSError, json.JSONDecodeError):
        return None


# ---------------------------------------------------------------- environment

def _settings(claude_home: Path) -> dict[str, Any]:
    merged: dict[str, Any] = {}
    for name in ("settings.json", "settings.local.json"):
        path = claude_home / name
        if path.is_file():
            try:
                data = json.loads(path.read_text(encoding="utf-8-sig"))
            except (OSError, json.JSONDecodeError) as exc:
                merged.setdefault("_errors", []).append(f"{path}: {exc}")
                continue
            if isinstance(data, dict):
                env = {**merged.get("env", {}), **(data.get("env") or {})}
                merged.update(data)
                merged["env"] = env
    return merged


def environment_checks(claude_home: Path, profile: Mapping[str, Any] | None) -> list[dict[str, Any]]:
    """Settings that silently override per-role choices."""
    settings = _settings(claude_home)
    env = {**(settings.get("env") or {}), **{k: v for k, v in os.environ.items() if k.startswith("CLAUDE_CODE_")}}
    checks: list[dict[str, Any]] = []
    if env.get("CLAUDE_CODE_EFFORT_LEVEL"):
        checks.append({"level": "blocking", "code": "effort_env_overrides_all_roles",
                       "detail": f"CLAUDE_CODE_EFFORT_LEVEL={env['CLAUDE_CODE_EFFORT_LEVEL']} beats every per-role effort"})
    if env.get("CLAUDE_CODE_SUBAGENT_MODEL_FORCE"):
        checks.append({"level": "blocking", "code": "subagent_model_forced",
                       "detail": "CLAUDE_CODE_SUBAGENT_MODEL_FORCE ignores per-role model parameters"})
    elif env.get("CLAUDE_CODE_SUBAGENT_MODEL"):
        checks.append({"level": "info", "code": "subagent_model_env_default",
                       "detail": "applies only to roles left on inherit without an agent-file model"})
    allowed = settings.get("availableModels")
    if isinstance(allowed, list) and profile is not None:
        for role, cfg in profile["roles"].items():
            for choice in [cfg, *cfg["fallbacks"]]:
                model = choice["model"]
                if model != INHERIT and not any(model == a or model.startswith(str(a)) for a in allowed):
                    checks.append({"level": "warning", "code": "model_outside_available_models",
                                   "detail": f"{role}: {model} not in user availableModels; Claude Code substitutes"})
    for name in ("Explore", "Plan", "general-purpose"):
        if (claude_home / "agents" / f"{name}.md").exists():
            checks.append({"level": "info", "code": "builtin_overridden_by_user_agent",
                           "detail": f"agents/{name}.md replaces the built-in {name} prompt"})
    if (claude_home.parent / ".cursor").is_dir():
        checks.append({"level": "warning", "code": "cursor_reads_claude_agents",
                       "detail": "Cursor also loads ~/.claude/agents; create same-named ~/.cursor/agents/team-*.md "
                                 "with Cursor model IDs (see adapters/cursor.md) so aliases like opus are not misread"})
    if settings.get("_errors"):
        checks.append({"level": "warning", "code": "settings_unreadable", "detail": settings["_errors"]})
    checks.append({"level": "info", "code": "managed_or_project_settings_not_read",
                   "detail": "managed policy, project settings and agent.spawn mods can still override; verify with a probe"})
    return checks


