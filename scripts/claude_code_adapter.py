# ---------------------------------------------------------------- error classes, cooldown, recovery

# Ordered: the first matching class wins. Patterns follow the errors hosts and
# providers actually print (HTTP status, Anthropic/OpenAI wording).
ERROR_CLASSES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("workspace_quota_exceeded", ("organization's usage limit", "workspace limit", "monthly spend limit",
                                  "workspace quota", "billing hard limit")),
    ("quota_exceeded", ("quota", "usage limit", "credit balance", "insufficient credit", "out of credits",
                        "limit reached", "weekly limit", "5-hour limit")),
    ("rate_limit", ("429", "rate limit", "rate_limit", "too many requests", "requests per minute")),
    ("overloaded", ("529", "503", "overloaded", "service unavailable", "capacity")),
    ("model_not_found", ("model not found", "not_found_error", "model is not available", "unknown model",
                         "model not supported", "does not have access to model", "invalid model")),
    ("auth", ("401", "403", "invalid api key", "authentication", "unauthorized", "permission denied",
              "not logged in")),
    ("network", ("econnreset", "etimedout", "enotfound", "socket hang up", "network", "connection reset",
                 "timed out")),
    ("server_error", ("500", "502", "504", "internal server error", "bad gateway", "gateway timeout")),
)
SWITCH_NOW = {"quota_exceeded", "rate_limit", "overloaded", "model_not_found"}
COOLDOWN_SECONDS = {"quota_exceeded": 3600, "rate_limit": 120, "overloaded": 300, "model_not_found": 86400}
ADVICE = {
    "workspace_quota_exceeded": "account/workspace total exhausted: report; switching models does not help",
    "auth": "credentials or permissions: report; not a model problem",
    "network": "retry the same model after the connection recovers",
    "server_error": "retry the same model once; switch only if it repeats",
    "unknown": "read the error; do not switch without a known cause",
}


def classify_error(text: str) -> dict[str, Any]:
    lowered = text.casefold()
    reason = next((name for name, needles in ERROR_CLASSES if any(n in lowered for n in needles)), "unknown")
    return {"reason": reason, "switch": reason in SWITCH_NOW,
            "cooldown_seconds": COOLDOWN_SECONDS.get(reason),
            "advice": "switch to the next fallback" if reason in SWITCH_NOW else ADVICE[reason]}


def _cooldowns(state_dir: Path) -> dict[str, Any]:
    path = state_dir / "cooldowns.json"
    return _read_json(path, "cooldowns") if path.exists() else {}


def recovery_status(state_dir: Path, profile: Mapping[str, Any]) -> dict[str, Any]:
    now = time.time()
    status = {}
    for role, cfg in profile["roles"].items():
        if cfg["active_index"] == 0:
            continue
        until = _cooldowns(state_dir).get(role, {}).get("until", 0)
        status[role] = {"active_index": cfg["active_index"], "primary": cfg["model"],
                        "cooldown_until": until, "primary_recoverable": now >= until}
    return status


def cmd_classify(text: str) -> int:
    emit({"status": "ok", **classify_error(text)})
    return 0


def cmd_recover(role_arg: str, force: bool, state_dir: Path, claude_home: Path,
                catalog: dict[str, set[str]]) -> int:
    profile = load_profile(state_dir, None)
    targets = list(ROLE_NAMES) if role_arg.casefold() == "all" else [resolve_role(role_arg, claude_home, None)["role"]]
    status = recovery_status(state_dir, profile)
    restored, waiting = [], {}
    updated = json.loads(json.dumps(profile))
    for role in targets:
        if role not in status:
            continue
        if force or status[role]["primary_recoverable"]:
            updated["roles"][role]["active_index"] = 0
            restored.append(role)
        else:
            waiting[role] = status[role]["cooldown_until"]
    outputs: dict[Path, bytes] = {}
    if restored:
        updated = normalize_profile(updated, catalog)
        cooldowns = _cooldowns(state_dir)
        for role in restored:
            cooldowns.pop(role, None)
        outputs[_profile_path(state_dir)] = serialize_profile(updated)
        outputs[state_dir / "cooldowns.json"] = _dump(cooldowns)
        outputs.update(host_outputs(state_dir, claude_home, updated))
    backups = commit_files(outputs, state_dir) if outputs else []
    emit({"status": "ok", "restored_to_primary": restored, "still_cooling": waiting, "backup_files": backups})
    return 0


