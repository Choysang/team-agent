def parse_frontmatter(text: str) -> tuple[dict[str, str], list[str], list[str]] | None:
    lines = text.lstrip("﻿").splitlines(keepends=True)
    if not lines or lines[0].strip() != "---":
        return None
    for end in range(1, len(lines)):
        if lines[end].strip() == "---":
            front = lines[1:end]
            fields = {}
            for line in front:
                if line[:1].isspace() or ":" not in line or line.lstrip().startswith("#"):
                    continue
                key, value = line.split(":", 1)
                fields[key.strip()] = value.split(" #", 1)[0].strip().strip("'\"")
            return fields, front, lines[end:]
    return None


def scan_agents(claude_home: Path) -> list[dict[str, Any]]:
    result = []
    folder = claude_home / "agents"
    if not folder.is_dir():
        return result
    for path in sorted(folder.glob("*.md")):
        try:
            parsed = parse_frontmatter(path.read_text(encoding="utf-8"))
        except OSError as exc:
            result.append({"host_role": path.stem, "file": str(path), "error": str(exc)})
            continue
        if parsed is None:
            result.append({"host_role": path.stem, "file": str(path), "error": "no_frontmatter"})
            continue
        fields, front, body = parsed
        name = fields.get("name") or path.stem
        if any(TEAM_FILE_MARK in line for line in body):
            continue  # generated team-* files are routed by role, not as specialists
        builtin = BUILTIN_TYPES.get(name.casefold())
        mapped = builtin or infer_host_role(name, path.stem)
        managed = any(MANAGED_TAG in line for line in front)
        result.append({
            "host_role": name, "file": str(path),
            "mapped_role": mapped or "GeneralWorker",
            "classification_source": "builtin_name" if builtin else "name_hint" if mapped else "fallback",
            "explicit_override": {k: fields[k] for k in ("model", "effort") if fields.get(k)},
            "managed_binding": managed,
        })
    return result


def plan_bindings(claude_home: Path, profile: Mapping[str, Any]) -> dict[Path, bytes]:
    """Managed model/effort frontmatter for existing specialist agent files."""
    outputs: dict[Path, bytes] = {}
    for agent in scan_agents(claude_home):
        if "error" in agent or agent["host_role"].casefold() in BUILTIN_TYPES:
            continue
        path = Path(agent["file"])
        fields, front, rest = parse_frontmatter(path.read_text(encoding="utf-8"))  # type: ignore[misc]
        kept = [line for line in front if MANAGED_TAG not in line]
        if any(line.split(":", 1)[0].strip() in ("model", "effort") for line in kept if not line[:1].isspace()):
            raise AdapterError(f"existing explicit model/effort needs reconciliation first: {path}")
        choice = active_choice(profile["roles"][agent["mapped_role"]])
        managed = []
        if choice["model"] != INHERIT:
            managed.append(f"model: {choice['model']}  {MANAGED_TAG}\n")
        if choice["effort"] != INHERIT:
            managed.append(f"effort: {choice['effort']}  {MANAGED_TAG}\n")
        newline = "\r\n" if front and front[0].endswith("\r\n") else "\n"
        managed = [line.replace("\n", newline) for line in managed]
        outputs[path] = ("---" + newline + "".join(kept + managed) + "".join(rest)).encode("utf-8")
    return outputs


# ---------------------------------------------------------------- routing block

def _param(value: str) -> str:
    return "不传（继承）" if value == INHERIT else f"`{value}`"


def render_block(profile: Mapping[str, Any], revision: str) -> str:
    rows = []
    for role in ROLE_NAMES:
        cfg = profile["roles"][role]
        choice = active_choice(cfg)
        # chain = [primary, *fallbacks]; entries after the active one remain.
        remaining = [f"{c['model']}/{c['effort']}" for c in cfg["fallbacks"][cfg["active_index"]:]]
        rows.append(f"| {role} | {ROLE_DUTY[role]} | `{DEFAULT_AGENT_TYPE[role]}` | {_param(choice['model'])} "
                    f"| {_param(choice['effort'])} | {', '.join(remaining) or '无'} |")
    return "\n".join([
        BLOCK_START,
        "## Team Agent 子代理路由（由 team-agent 生成，请勿手改本块）",
        "",
        "是否派发子代理由你自己判断，本表不要求多派。用户已为下列职能明确指定子代理的模型与思考强度；"
        "派发时先判断职能，使用表中的 subagent_type，"
        "并传表中的 `model` 与 `effort`；这属于用户明确要求的思考强度。team-agent-router mod加载时，"
        "它会自动补上缺失参数；你显式传的值（例如升级时）会被保留。",
        "",
        "| 职能 | 用途 | subagent_type | model | effort | 剩余备选（按序） |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        "规则：",
        "- 已有更专业的子代理类型（例如 code-reviewer、python-reviewer）时保留该类型，传其职能的 model/effort。",
        "- “不传（继承）”表示省略该参数。",
        "- 不用 fork 承担上述职能：fork 不接受 effort 且继承主模型，除非用户明确要求 fork。",
        "- 无法归类的任务用 GeneralWorker 行；用户在当次请求中另行指定时以用户为准。",
        "- 结果不合格（能力不足）时逐级升级，每级新建调用：同一模型按 medium→high→xhigh→max 调高强度，"
        "到顶后换更强的模型（haiku→sonnet→opus→fable）再从 medium 开始；"
        "缺上下文先补上下文，不算升级。阶梯可用 `claude_code_adapter.py ladder --role <职能>` 生成。",
        "- 额度或限流失败：切到下一个备选并新建调用，不重试同一失败；无备选则报告阻塞。网络、权限错误不切换模型。",
        f"- profile revision: `{revision[:12]}`",
        BLOCK_END,
    ])


def render_team_file(role: str, choice: Mapping[str, str]) -> bytes:
    description, disallowed, body = TEAM_FILE_TEXT[role]
    lines = ["---", f"name: team-{role.lower()}", f"description: {description}"]
    if disallowed:
        lines.append(f"disallowedTools: {disallowed}")
    if choice["model"] != INHERIT:
        lines.append(f"model: {choice['model']}")
    if choice["effort"] != INHERIT:
        lines.append(f"effort: {choice['effort']}")
    lines += ["---", "", body, "", TEAM_FILE_MARK, ""]
    return "\n".join(lines).encode("utf-8")


def routing_table(claude_home: Path, profile: Mapping[str, Any]) -> dict[str, Any]:
    """agent type (lower-case) -> active model/effort, consumed by the team-agent-router mod."""
    agents: dict[str, Any] = {}

    def add(agent_type: str, role: str) -> None:
        choice = active_choice(profile["roles"][role])
        agents[agent_type.casefold()] = {"role": role, "model": choice["model"], "effort": choice["effort"]}

    for agent in scan_agents(claude_home):
        if "error" not in agent:
            add(agent["host_role"], agent["mapped_role"])
    for builtin, role in BUILTIN_TYPES.items():
        add(builtin, role)
    for role, agent_type in DEFAULT_AGENT_TYPE.items():
        add(agent_type, role)
    return {"revision": profile_revision(profile), "agents": dict(sorted(agents.items()))}



def apply_block(existing: str, block: str) -> str:
    start, end = existing.find(BLOCK_START), existing.find(BLOCK_END)
    if (start < 0) != (end < 0) or (start >= 0 and end < start):
        raise AdapterError("CLAUDE.md has an incomplete team-agent routing block; fix it manually first")
    if start >= 0:
        return existing[:start] + block + existing[end + len(BLOCK_END):]
    if not existing or existing.endswith("\n\n"):
        separator = ""
    else:
        separator = "\n" if existing.endswith("\n") else "\n\n"
    return existing + separator + block + "\n"


def _claude_md(claude_home: Path) -> Path:
    return claude_home / "CLAUDE.md"


def _read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8-sig") if path.exists() else ""
    except OSError as exc:
        raise AdapterError(f"cannot read {path}: {exc}") from exc


def host_outputs(state_dir: Path, claude_home: Path, profile: dict[str, Any]) -> dict[Path, bytes]:
    revision = profile_revision(profile)
    md = _claude_md(claude_home)
    outputs = {md: apply_block(_read_text(md), render_block(profile, revision)).encode("utf-8")}
    for role in TEAM_FILE_ROLES:
        path = claude_home / "agents" / f"team-{role.lower()}.md"
        if path.exists() and TEAM_FILE_MARK not in _read_text(path):
            raise AdapterError(f"{path} exists and was not generated by team-agent; rename it first")
        outputs[path] = render_team_file(role, active_choice(profile["roles"][role]))
    outputs[state_dir / "routing.json"] = _dump(routing_table(claude_home, profile))
    marker = state_dir / "host-bindings.json"
    if marker.exists() and _read_json(marker, "binding state").get("enabled") is True:
        outputs.update(plan_bindings(claude_home, profile))
    return outputs


