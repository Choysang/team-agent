def _recent_subagents(claude_home: Path, days: float) -> list[dict[str, Any]]:
    cutoff = time.time() - days * 86400
    rows = []
    for meta_path in claude_home.glob("projects/*/*/subagents/agent-*.meta.json"):
        try:
            if meta_path.stat().st_mtime < cutoff:
                continue
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        actual, efforts, tokens = set(), set(), 0
        for line in _iter_lines(meta_path.with_name(meta_path.name.replace(".meta.json", ".jsonl"))):
            if line.get("type") == "assistant":
                message = line.get("message") or {}
                actual.add(message.get("model") or line.get("requestedModel"))
                efforts.add(line.get("effort"))
                usage = message.get("usage") or {}
                tokens += int(usage.get("output_tokens") or 0)
        rows.append({"agent_type": meta.get("agentType"), "requested_model": meta.get("model"),
                     "requested_effort": meta.get("effort"), "models": sorted(filter(None, actual)),
                     "efforts": sorted(filter(None, efforts)), "output_tokens": tokens})
    return rows


def cmd_stats(state_dir: Path, claude_home: Path, days: float) -> int:
    table = _read_json(state_dir / "routing.json", "routing table") if (state_dir / "routing.json").exists() else {"agents": {}}
    groups: dict[str, dict[str, Any]] = {}
    deviations = []
    for row in _recent_subagents(claude_home, days):
        agent_type = str(row["agent_type"] or "general-purpose")
        route = table["agents"].get(agent_type.casefold(), {})
        group = groups.setdefault(agent_type, {"role": route.get("role"), "dispatches": 0, "models": {},
                                               "efforts": {}, "output_tokens": 0})
        group["dispatches"] += 1
        group["output_tokens"] += row["output_tokens"]
        for model in row["models"] or ["?"]:
            group["models"][model] = group["models"].get(model, 0) + 1
        for effort in row["efforts"] or ["?"]:
            group["efforts"][effort] = group["efforts"].get(effort, 0) + 1
        want_model, want_effort = route.get("model"), route.get("effort")
        if want_model and want_model != INHERIT and not all(
                m.startswith(_expected_model_prefix(want_model, []) or "") for m in row["models"]):
            deviations.append({"agent_type": agent_type, "expected_model": want_model, "observed": row["models"]})
        elif want_effort and want_effort != INHERIT and row["efforts"] and row["efforts"] != [want_effort]:
            deviations.append({"agent_type": agent_type, "expected_effort": want_effort, "observed": row["efforts"]})
    emit({"status": "ok", "days": days, "by_agent_type": groups, "deviations": deviations,
          "scope": "observed subagent transcripts only; tokens are output tokens, no prices are modelled"})
    return 0


