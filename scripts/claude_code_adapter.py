def _expected_model_prefix(model: str, models: list[dict[str, Any]]) -> str | None:
    if model == INHERIT:
        return None
    if model.startswith("claude-"):
        return model
    return f"claude-{model}-"


def cmd_probe_prepare(manifest: Path, state_dir: Path, claude_home: Path, loaded: set[str] | None) -> int:
    profile = load_profile(state_dir, None)
    expected = {}
    for role in ROLE_NAMES:
        choice = active_choice(profile["roles"][role])
        expected[role] = {"agent_type": resolve_role(role, claude_home, loaded)["agent_type"], **choice}
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(json.dumps({"host": HOST, "started_at": time.time(),
                                    "configuration_sha256": profile_revision(profile),
                                    "expected": expected, "agents": {}}, ensure_ascii=False, indent=2) + "\n",
                        encoding="utf-8")
    emit({"status": "prepared", "manifest": str(manifest),
          "next": "dispatch one NEW minimal call per role using the routing table, then put each agentId into agents{role: id}"})
    return 0


def _parse_ts(value: Any) -> float | None:
    if not isinstance(value, str):
        return None
    try:
        return dt.datetime.fromisoformat(value.replace("Z", "+00:00")).timestamp()
    except ValueError:
        return None


def inspect_agent(claude_home: Path, agent_id: str, expected: Mapping[str, str], started_at: float) -> dict[str, Any]:
    result: dict[str, Any] = {"agent_id": agent_id, "expected": dict(expected), "status": "unverified",
                              "evidence": "claude_code_subagent_transcript"}
    metas = list(claude_home.glob(f"projects/*/*/subagents/agent-{agent_id}.meta.json"))
    if len(metas) != 1:
        return {**result, "reason": "agent_transcript_not_found" if not metas else "agent_id_ambiguous"}
    meta = json.loads(metas[0].read_text(encoding="utf-8"))
    result["requested"] = {k: meta.get(k) for k in ("agentType", "model", "effort")}
    if str(meta.get("agentType", "")).casefold() != expected["agent_type"].casefold():
        return {**result, "status": "mismatch", "reason": "agent_type_mismatch"}
    for key in ("model", "effort"):
        want = None if expected[key] == INHERIT else expected[key]
        if want is not None and meta.get(key) != want:
            return {**result, "status": "mismatch", "reason": f"requested_{key}_mismatch"}
    prefix = _expected_model_prefix(expected["model"], [])
    observed_models, observed_efforts, outputs, first_ts = set(), set(), 0, None
    for line in _iter_lines(metas[0].with_name(f"agent-{agent_id}.jsonl")):
        if line.get("type") != "assistant":
            continue
        first_ts = first_ts if first_ts is not None else _parse_ts(line.get("timestamp"))
        model = (line.get("message") or {}).get("model") or line.get("requestedModel")
        observed_models.add(model)
        observed_efforts.add(line.get("effort"))
        content = (line.get("message") or {}).get("content") or []
        outputs += any(isinstance(c, dict) and c.get("type") in ("text", "tool_use") for c in content)
    result["observed"] = {"models": sorted(filter(None, observed_models)),
                          "efforts": sorted(filter(None, observed_efforts))}
    if not outputs:
        return {**result, "reason": "no_completed_model_output_observed"}
    if first_ts is None or first_ts < started_at - 1:
        return {**result, "reason": "agent_predates_this_test"}
    if prefix and not all(isinstance(m, str) and m.startswith(prefix) for m in observed_models):
        return {**result, "status": "mismatch", "reason": "observed_model_mismatch"}
    if expected["effort"] != INHERIT and observed_efforts != {expected["effort"]}:
        return {**result, "status": "mismatch", "reason": "observed_effort_mismatch",
                "note": "Claude Code lowers unsupported levels to the highest supported one"}
    return {**result, "status": "pass",
            "scope": "host_selected_agent_type_model_and_effort_not_task_quality"}


def cmd_probe_check(manifest_path: Path, state_dir: Path, claude_home: Path) -> int:
    manifest = _read_json(manifest_path, "probe manifest")
    profile = load_profile(state_dir, None)
    if manifest.get("configuration_sha256") != profile_revision(profile):
        report = {"status": "incomplete", "reason": "configuration_changed_since_prepare", "checks": []}
    else:
        checks, seen = [], set()
        for role, expected in manifest["expected"].items():
            agent_id = manifest.get("agents", {}).get(role)
            if not agent_id and expected["model"] == INHERIT and expected["effort"] == INHERIT:
                # Nothing is configured for this role; host defaults are not under test.
                checks.append({"role": role, "status": "not_configured", "reason": "inherit_inherit"})
            elif not agent_id:
                checks.append({"role": role, "status": "unverified", "reason": "no_agent_id_supplied"})
            elif agent_id in seen:
                checks.append({"role": role, "status": "unverified", "reason": "agent_reused_for_another_role"})
            else:
                seen.add(agent_id)
                checks.append({"role": role, **inspect_agent(claude_home, agent_id, expected, manifest["started_at"])})
        tested = [c for c in checks if c["status"] != "not_configured"]
        report = {"status": "pass" if tested and all(c["status"] == "pass" for c in tested) else "incomplete",
                  "configuration_sha256": manifest["configuration_sha256"], "checks": checks}
    commit_files({state_dir / "runtime-verification.json": _dump(report)}, state_dir)
    emit(report)
    return 0 if report["status"] == "pass" else 1


