def cmd_failover(role_arg: str, reason_arg: str, event_id: str, state_dir: Path, claude_home: Path,
                 catalog: dict[str, set[str]]) -> int:
    if not event_id or len(event_id) > 256:
        raise AdapterError("event-id must be non-empty and at most 256 characters")
    reason = reason_arg.strip().casefold()
    events_path = state_dir / "failover_events.json"
    events = _read_json(events_path, "failover events") if events_path.exists() else {"version": 1, "events": {}}
    request = {"role": role_arg, "reason": reason}
    if event_id in events["events"]:
        existing = events["events"][event_id]
        if existing["request"] != request:
            raise AdapterError("event-id was already used with a different role or reason")
        emit({**existing["result"], "idempotent_replay": True})
        return 0
    profile = load_profile(state_dir, None)
    role = resolve_role(role_arg, claude_home, None)["role"]
    cfg = profile["roles"][role]
    active = active_choice(cfg)
    base = {"role": role, "reason": reason, "active_model": active["model"], "active_effort": active["effort"]}
    outputs: dict[Path, bytes] = {}
    if reason in GLOBAL_QUOTA_REASONS:
        result = {"status": "blocked", "code": "workspace_quota_blocked", **base}
    elif reason not in SWITCHABLE_REASONS | SWITCH_NOW:
        result = {"status": "blocked", "code": "reason_not_switchable", **base,
                  "advice": ADVICE.get(reason, ADVICE["unknown"])}
    elif cfg["active_index"] >= len(cfg["fallbacks"]):
        result = {"status": "blocked", "code": "no_fallback_remaining", **base}
    else:
        updated = json.loads(json.dumps(profile))
        updated["roles"][role]["active_index"] += 1
        updated = normalize_profile(updated, catalog)
        choice = active_choice(updated["roles"][role])
        result = {"status": "failed_over", "role": role, "reason": reason,
                  "previous_model": active["model"], "active_model": choice["model"],
                  "active_effort": choice["effort"], "active_index": updated["roles"][role]["active_index"]}
        outputs[_profile_path(state_dir)] = serialize_profile(updated)
        outputs.update(host_outputs(state_dir, claude_home, updated))
        cooldowns = _cooldowns(state_dir)
        if role not in cooldowns:  # keep the first failure's clock for the primary
            cooldowns[role] = {"model": cfg["model"], "reason": reason,
                               "until": time.time() + COOLDOWN_SECONDS.get(reason, 3600)}
            outputs[state_dir / "cooldowns.json"] = _dump(cooldowns)
        result["primary_retry_after"] = cooldowns[role]["until"]
    events["events"][event_id] = {"request": request, "result": result}
    outputs[events_path] = _dump(events)
    backups = commit_files(outputs, state_dir)
    emit({**result, "event_id": event_id, "backup_files": backups})
    return 0


def cmd_catalog_ack(fingerprint: str, decision: str, roles_arg: str, state_dir: Path) -> int:
    path = state_dir / "catalog_state.json"
    state = _read_json(path, "catalog state")
    if fingerprint in state["acknowledged"]:
        emit({"status": "already_acknowledged", "fingerprint": fingerprint, **state["acknowledged"][fingerprint]})
        return 0
    if not any(item.get("fingerprint") == fingerprint for item in state["pending"]):
        raise AdapterError("fingerprint is not pending")
    selected = _csv(roles_arg) or []
    if decision == "selected":
        if not selected or any(r not in ROLE_NAMES for r in selected) or len(set(selected)) != len(selected):
            raise AdapterError("decision=selected needs unique roles from " + ", ".join(ROLE_NAMES))
    elif selected:
        raise AdapterError("decision=defer does not accept --roles")
    state["acknowledged"][fingerprint] = {"decision": decision, "selected_roles": selected,
                                          "acknowledged_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
    state["pending"] = [p for p in state["pending"] if p.get("fingerprint") != fingerprint]
    commit_files({path: _dump(state)}, state_dir)
    global CATALOG_NOTICE
    CATALOG_NOTICE = {"status": "pending_change" if state["pending"] else "unchanged",
                      "fingerprint": state["last_seen_fingerprint"], "pending": state["pending"]}
    emit({"status": "acknowledged", "fingerprint": fingerprint, "decision": decision,
          "selected_roles": selected, "profile_updated": False})
    return 0


