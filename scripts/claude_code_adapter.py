def resolve_role(requested: str, claude_home: Path, loaded: set[str] | None) -> dict[str, Any]:
    agents = [a for a in scan_agents(claude_home) if "error" not in a]
    lowered = requested.casefold()
    role = next((r for r in ROLE_NAMES if r.casefold() == lowered), None)

    def status(agent_type: str) -> str:
        return "unverified" if loaded is None else "loaded" if agent_type.casefold() in loaded else "not_loaded"

    if role is not None:
        for candidate in SPECIALIST_CANDIDATES.get(role, ()):
            on_disk = any(a["host_role"].casefold() == candidate for a in agents)
            if (loaded is not None and candidate in loaded) or (loaded is None and on_disk):
                return {"role": role, "agent_type": candidate, "fallback": False,
                        "source": "specialist", "current_session_status": status(candidate)}
        agent_type = DEFAULT_AGENT_TYPE[role]
        return {"role": role, "agent_type": agent_type, "fallback": False,
                "source": "builtin", "current_session_status": status(agent_type)}
    if lowered in BUILTIN_TYPES:
        canonical = {"explore": "Explore", "plan": "Plan"}.get(lowered, lowered)
        return {"role": BUILTIN_TYPES[lowered], "agent_type": canonical, "fallback": False,
                "source": "builtin", "current_session_status": status(canonical)}
    match = next((a for a in agents if a["host_role"].casefold() == lowered), None)
    if match is not None:
        return {"role": match["mapped_role"], "agent_type": match["host_role"],
                "fallback": match["classification_source"] == "fallback", "source": "agent_file",
                "host_override": match["explicit_override"], "current_session_status": status(match["host_role"])}
    if loaded is not None and lowered in loaded:
        mapped = infer_host_role(requested, requested)
        return {"role": mapped or "GeneralWorker", "agent_type": requested, "fallback": mapped is None,
                "source": "loaded_type", "current_session_status": "loaded"}
    fallback_type = DEFAULT_AGENT_TYPE["GeneralWorker"]
    return {"role": "GeneralWorker", "agent_type": fallback_type, "fallback": True,
            "source": "fallback", "current_session_status": status(fallback_type)}


