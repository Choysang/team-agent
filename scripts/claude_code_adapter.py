def build_parser() -> argparse.ArgumentParser:
    default_home = os.environ.get("CLAUDE_CONFIG_DIR") or str(Path.home() / ".claude")
    parser = JsonArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--claude-home", default=default_home)
    parser.add_argument("--state-dir", default=str(Path.home() / ".team-agent" / "claude-code"))
    parser.add_argument("--provider", default="anthropic", choices=["anthropic", "other"],
                        help="alias table is only documented for the Anthropic API provider")
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("models", "onboarding"):
        p = sub.add_parser(name)
        p.add_argument("--dispatch-models", help="model enum of the current Agent tool, comma-separated")
        p.add_argument("--dispatch-efforts", help="effort enum of the current Agent tool, comma-separated")
    sub.add_parser("sync").add_argument("--profile", required=True)
    for name in ("resolve", "verify"):
        p = sub.add_parser(name)
        p.add_argument("--loaded-agent-types")
        if name == "resolve":
            p.add_argument("--role", required=True)
    p = sub.add_parser("preference")
    p.add_argument("--role", required=True)
    p.add_argument("--skip-fallback-prompts", required=True, choices=["true", "false"])
    p = sub.add_parser("failover")
    p.add_argument("--role", required=True)
    p.add_argument("--reason", required=True)
    p.add_argument("--event-id", required=True)
    p = sub.add_parser("catalog-ack")
    p.add_argument("--fingerprint", required=True)
    p.add_argument("--decision", required=True, choices=["selected", "defer"])
    p.add_argument("--roles", default="")
    sub.add_parser("bind").add_argument("--disable", action="store_true")
    p = sub.add_parser("ladder", help="escalation rungs after an unacceptable result")
    p.add_argument("--role", required=True)
    p.add_argument("--from", dest="from_rung", help="<model>/<effort> that just failed; default: the role's active choice")
    sub.add_parser("classify", help="classify a dispatch error message").add_argument("--text", required=True)
    p = sub.add_parser("recover", help="return roles to their primary model after cooldown")
    p.add_argument("--role", required=True)
    p.add_argument("--force", action="store_true")
    sub.add_parser("stats", help="observed subagent dispatches by type and model").add_argument(
        "--days", type=float, default=7)
    p = sub.add_parser("probe")
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--prepare", type=Path)
    mode.add_argument("--check", type=Path)
    p.add_argument("--loaded-agent-types")
    return parser


def run(args: argparse.Namespace, state_dir: Path, claude_home: Path) -> int:
    global CATALOG_NOTICE
    if args.command in ("models", "onboarding") and (args.dispatch_models or args.dispatch_efforts):
        current = dispatch_enum(state_dir)
        commit_files({_dispatch_path(state_dir): _dump({
            "models": _csv(args.dispatch_models) or current["models"],
            "efforts": _csv(args.dispatch_efforts) or current["efforts"],
            "recorded_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())})}, state_dir)
    models = build_catalog(state_dir, claude_home, args.provider)
    catalog = catalog_sets(models)
    if args.command not in ("preference", "catalog-ack"):
        CATALOG_NOTICE = check_catalog(state_dir, models)
    loaded = {t.casefold() for t in _csv(getattr(args, "loaded_agent_types", None)) or []} \
        if getattr(args, "loaded_agent_types", None) is not None else None
    if args.command in ("models", "onboarding"):
        return cmd_models(state_dir, claude_home, models)
    if args.command == "sync":
        return cmd_sync(Path(args.profile).expanduser(), state_dir, claude_home, catalog)
    if args.command == "resolve":
        return cmd_resolve(args.role, state_dir, claude_home, catalog, loaded)
    if args.command == "verify":
        return cmd_verify(state_dir, claude_home, catalog, loaded)
    if args.command == "preference":
        return cmd_preference(args.role, args.skip_fallback_prompts == "true", state_dir)
    if args.command == "failover":
        return cmd_failover(args.role, args.reason, args.event_id, state_dir, claude_home, catalog)
    if args.command == "catalog-ack":
        return cmd_catalog_ack(args.fingerprint, args.decision, args.roles, state_dir)
    if args.command == "bind":
        return cmd_bind(state_dir, claude_home, not args.disable)
    if args.command == "classify":
        return cmd_classify(args.text)
    if args.command == "recover":
        return cmd_recover(args.role, args.force, state_dir, claude_home, catalog)
    if args.command == "stats":
        return cmd_stats(state_dir, claude_home, args.days)
    if args.command == "ladder":
        return cmd_ladder(args.role, args.from_rung, state_dir, claude_home, models)
    if args.command == "probe":
        if args.prepare:
            return cmd_probe_prepare(args.prepare, state_dir, claude_home, loaded)
        return cmd_probe_check(args.check, state_dir, claude_home)
    raise AdapterError(f"unknown command: {args.command}")


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    state_dir = Path(args.state_dir).expanduser()
    claude_home = Path(args.claude_home).expanduser()
    try:
        with state_lock(state_dir):
            return run(args, state_dir, claude_home)
    except (AdapterError, ValueError, KeyError, TypeError) as exc:
        emit({"status": "error", "error": f"{type(exc).__name__}: {exc}" if not isinstance(exc, AdapterError) else str(exc)})
        return 1
    except TimeoutError as exc:
        emit({"status": "error", "error": str(exc)})
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
