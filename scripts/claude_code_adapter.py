# ---------------------------------------------------------------- escalation ladder

MODEL_ORDER = ("haiku", "sonnet", "opus", "fable")  # Claude Code aliases, weakest first
LADDER_FLOOR = "medium"


def build_ladder(start_model: str, start_effort: str, models: list[dict[str, Any]]) -> list[dict[str, str]]:
    """Same model with rising effort, then each stronger model from medium up."""
    levels = {m["slug"]: [e for e in EFFORT_LEVELS if e in (m["supported_reasoning_levels"] or [])] for m in models}
    available = [m for m in MODEL_ORDER if m in levels] + [m for m in levels if m not in MODEL_ORDER]
    if start_model not in levels:
        raise AdapterError(f"{start_model} is not a dispatchable model here; pass --from <model>/<effort>")
    floor = EFFORT_LEVELS.index(LADDER_FLOOR)
    current = start_effort if start_effort in EFFORT_LEVELS else LADDER_FLOOR
    rungs = [{"model": start_model, "effort": current}]
    for effort in levels[start_model]:
        index = EFFORT_LEVELS.index(effort)
        if index > EFFORT_LEVELS.index(current) and index >= floor:
            rungs.append({"model": start_model, "effort": effort})
    start = available.index(start_model)
    for model in available[start + 1:] if start_model in MODEL_ORDER else []:
        for effort in levels[model]:
            if EFFORT_LEVELS.index(effort) >= floor:
                rungs.append({"model": model, "effort": effort})
    return rungs


def cmd_ladder(role_arg: str, from_arg: str | None, state_dir: Path, claude_home: Path,
               models: list[dict[str, Any]]) -> int:
    profile = load_profile(state_dir, None)
    role = resolve_role(role_arg, claude_home, None)["role"]
    base = active_choice(profile["roles"][role])
    if base["model"] == INHERIT and not from_arg:
        raise AdapterError(f"{role} inherits the session model; pass --from <current model>/<effort>")
    origin = dict(zip(("model", "effort"), from_arg.split("/", 1))) if from_arg else base
    origin.setdefault("effort", LADDER_FLOOR)
    rungs = build_ladder(origin["model"], origin["effort"], models)
    emit({"status": "ok", "role": role, "agent_type": resolve_role(role, claude_home, None)["agent_type"],
          "from": origin, "next": rungs[1] if len(rungs) > 1 else None, "ladder": rungs,
          "rule": "dispatch a NEW call with the next rung's model and effort; exhausted -> do it yourself or report"})
    return 0


